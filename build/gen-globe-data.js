/* Samples real land polygons into an evenly-spread dot matrix for the globe.
   Run:  npm install --no-save world-atlas topojson-client d3-geo
         node build/gen-globe-data.js
   Writes site/assets/js/globe-data.js (a base64 Int16Array of lat/lon x100). */
const fs = require('fs');
const path = require('path');
const topojson = require('topojson-client');
const { geoContains } = require('d3-geo');
const world = require('world-atlas/land-110m.json');

const land = topojson.feature(world, world.objects.land);

// Fibonacci sphere: equal-area point spread, so no crowding at the poles the
// way a naive lat/lon grid gives you.
const N = 14000;
const GOLDEN = Math.PI * (3 - Math.sqrt(5));
const pts = [];

for (let i = 0; i < N; i++) {
  const y = 1 - (i / (N - 1)) * 2;          // 1 .. -1
  const radius = Math.sqrt(Math.max(0, 1 - y * y));
  const theta = GOLDEN * i;
  const x = Math.cos(theta) * radius;
  const z = Math.sin(theta) * radius;

  const lat = Math.asin(y) * 180 / Math.PI;
  const lon = Math.atan2(z, x) * 180 / Math.PI;

  if (geoContains(land, [lon, lat])) pts.push([lat, lon]);
}

const buf = new Int16Array(pts.length * 2);
pts.forEach((p, i) => {
  buf[i * 2] = Math.round(p[0] * 100);
  buf[i * 2 + 1] = Math.round(p[1] * 100);
});

const b64 = Buffer.from(buf.buffer).toString('base64');
const out =
`/* Generated by build/gen-globe-data.js — do not edit by hand.
   ${pts.length} land points sampled from Natural Earth 110m land polygons,
   stored as Int16 lat/lon x100, little-endian, base64. */
window.OC_GLOBE_POINTS = "${b64}";
`;

fs.writeFileSync(path.join(__dirname, '..', 'site', 'assets', 'js', 'globe-data.js'), out);
console.log('sampled ' + N + ' sphere points -> ' + pts.length + ' on land');
console.log('written: ' + (out.length / 1024).toFixed(1) + ' kB (base64)');
